/// Zino's notification copy.
///
/// Kept as data, not string literals scattered through scheduling code, so the
/// voice stays consistent and the rotation is testable. Everything here is
/// written in Zino's register: warm, short, never nagging, never guilt-tripping
/// someone who missed a day.
library;

/// Deterministic index for a given day.
///
/// Day-of-year based rather than random, for two reasons: a notification
/// scheduled days ahead must produce the SAME text when it eventually fires
/// (a random pick at schedule time and another at display time would disagree),
/// and it makes "never the same two days running" provable rather than hoped
/// for — consecutive days are always different list positions.
int dayIndex(DateTime date) {
  final startOfYear = DateTime(date.year);
  return date.difference(startOfYear).inDays;
}

/// Picks from [items] for [date], guaranteeing consecutive days differ.
T pickForDay<T>(List<T> items, DateTime date) {
  if (items.isEmpty) throw ArgumentError('no messages to pick from');
  return items[dayIndex(date) % items.length];
}

